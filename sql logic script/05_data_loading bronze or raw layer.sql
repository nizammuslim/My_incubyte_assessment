FROM @INCUBYTE_ASSESSMENT.BRONZE.S3_INCUBYTE_STAG/JSON_DATA_FILE/
FILE_FORMAT = (FORMAT_NAME => 'INCUBYTE_ASSESSMENT.BRONZE.JSON_STANDARD')
ON_ERROR = CONTINUE;









