
USE ROLE ACCOUNTADMIN;

USE WAREHOUSE incubyte_wh;

USE DATABASE INCUBYTE_ASSESSMENT;

USE SCHEMA INCUBYTE_ASSESSMENT.BRONZE;


-- aws data loading to snowflake raw tables(.csv and .json files)

COPY INTO INCUBYTE_ASSESSMENT.BRONZE.RAW_MEMBERS
FROM @INCUBYTE_ASSESSMENT.BRONZE.S3_INCUBYTE_STAG/CSV_DATA_FILE/
