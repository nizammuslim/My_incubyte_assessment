CREATE OR REPLACE FUNCTION PARSE_MEMBER_DATE(TXT VARCHAR, SRC_COUNTRY VARCHAR)
RETURNS DATE
AS
$$
    COALESCE(
        CASE SRC_COUNTRY
            WHEN 'AUS' THEN TRY_TO_DATE(TXT, 'DD/MM/YYYY')
            WHEN 'USA' THEN TRY_TO_DATE(TXT, 'MM/DD/YYYY')
            WHEN 'IND' THEN TRY_TO_DATE(TXT, 'DD-MM-YYYY')
        END,
        TRY_TO_DATE(TXT, 'YYYY-MM-DD')
    )
$$;


