-- this function only need for all the country date formats changed the same format('YYYY-MM-DD')
SET AS_OF_DATE = CURRENT_DATE();
CREATE OR REPLACE FUNCTION PARSE_MEMBER_DATE(TXT VARCHAR, SRC_COUNTRY VARCHAR)
RETURNS DATE
AS
$$
    COALESCE(
        CASE SRC_COUNTRY
            WHEN 'AUS' THEN TRY_TO_DATE(TXT, 'DD/MM/YYYY')
            WHEN 'USA' THEN TRY_TO_DATE(TXT, 'MM/DD/YYYY')
            WHEN 'IND' THEN TRY_TO_DATE(TXT, 'DD-MM-YYYY')
        END,
        TRY_TO_DATE(TXT, 'YYYY-MM-DD')
    )
$$;


--  -  RAW_MEMBERS -> STG_MEMBERS (+ REJECTED_MEMBERS)

CREATE OR REPLACE TEMPORARY TABLE TMP_MEMBERS_PARSED AS
WITH cleaned AS (
    -- Step 1: trim spaces, turn blanks into NULL, turn text into real dates (bad text -> NULL, never an error)
    SELECT
        NULLIF(TRIM(MEMBER_ID), ''))  AS MEMBER_ID,
        NULLIF(TRIM(MEMBER_NAME), '') AS MEMBER_NAME,
        NULLIF(TRIM(EMAIL), '') AS EMAIL,
        NULLIF(TRIM(DOB), '') AS DOB_TEXT, 
        -- THIS PARSE_MEMBER_DATE i will manuaaly created the UDFunction
        PARSE_MEMBER_DATE(NULLIF(TRIM(DOB), ''), SOURCE_COUNTRY)            AS DOB,
        PARSE_MEMBER_DATE(NULLIF(TRIM(FLIGHT_DATE), ''), SOURCE_COUNTRY)    AS FLIGHT_DATE,
        COALESCE(
            CASE NULLIF(UPPER(TRIM(COUNTRY)), '')
                WHEN 'AUS' THEN 'AUS' WHEN 'AU' THEN 'AUS' WHEN 'AUSTRALIA' THEN 'AUS'
                WHEN 'USA' THEN 'USA' WHEN 'US' THEN 'USA'
                WHEN 'UNITED STATES' THEN 'USA' WHEN 'UNITED STATES OF AMERICA' THEN 'USA'
                WHEN 'IND' THEN 'IND' WHEN 'IN' THEN 'IND' WHEN 'INDIA' THEN 'IND'
                ELSE NULLIF(UPPER(TRIM(COUNTRY)), '')
            END,
            SOURCE_COUNTRY
        ) AS COUNTRY,
        NULLIF(TRIM(TIER), '') AS TIER,
        SOURCE_FILE,
        SOURCE_COUNTRY,
        SOURCE_ROW_NO
    FROM RAW_MEMBERS
),
DERIVED AS (
    SELECT
        CLEANED.*,
        CASE
            WHEN DOB IS NULL OR DOB > $AS_OF_DATE THEN NULL
            ELSE DATEDIFF(YEAR, DOB, $AS_OF_DATE)
                 - IFF(
                     MONTH(DOB) * 100 + DAY(DOB)
                       > MONTH($AS_OF_DATE) * 100 + DAY($AS_OF_DATE),
                     1, 0
                   )
        END AS AGE,
        CASE
            WHEN FLIGHT_DATE IS NULL THEN NULL
            WHEN FLIGHT_DATE > $AS_OF_DATE THEN NULL
            WHEN DATEDIFF(DAY, FLIGHT_DATE, $AS_OF_DATE) > 90 THEN 'Y'
            ELSE 'N'
        END AS STALE_MEMBER
FROM CLEANED
)
SELECT
    DERIVED.*,
    CASE
        WHEN MEMBER_ID IS NULL THEN 'MISSING_MEMBER_ID'
        WHEN MEMBER_NAME IS NULL THEN 'MISSING_MEMBER_NAME'
        WHEN DOB_TEXT IS NULL THEN 'MISSING_DOB'
        WHEN DOB IS NULL THEN 'INVALID_DOB'
        WHEN DOB > $AS_OF_DATE THEN 'DOB_IN_FUTURE'
        WHEN AGE > 120 THEN 'DOB_IMPLAUSIBLE'
        WHEN COUNTRY IS NULL OR COUNTRY NOT IN ('AUS', 'USA', 'IND')
            THEN 'UNKNOWN_COUNTRY'
        ELSE NULL
    END AS REJECT_REASON
FROM DERIVED;

--  Insert valid records into staging
INSERT INTO STG_MEMBERS (
    MEMBER_ID, MEMBER_NAME, EMAIL, DOB, COUNTRY, FLIGHT_DATE, TIER,
    AGE, STALE_MEMBER, SOURCE_FILE, SOURCE_COUNTRY, SOURCE_ROW_NO, AS_OF_DATE
)
SELECT
    MEMBER_ID, MEMBER_NAME, EMAIL, DOB, COUNTRY, FLIGHT_DATE, TIER,
    AGE, STALE_MEMBER, SOURCE_FILE, SOURCE_COUNTRY, SOURCE_ROW_NO, $AS_OF_DATE
FROM TMP_MEMBERS_PARSED
WHERE REJECT_REASON IS NULL;


--  Insert invalid records into the rejection table
INSERT INTO REJECTED_MEMBERS (
    MEMBER_ID, MEMBER_NAME, EMAIL, DOB, COUNTRY, FLIGHT_DATE, TIER,
    SOURCE_FILE, SOURCE_COUNTRY, SOURCE_ROW_NO, REJECT_REASON
)
SELECT
    MEMBER_ID, MEMBER_NAME, EMAIL, DOB, COUNTRY, FLIGHT_DATE, TIER,
    SOURCE_FILE, SOURCE_COUNTRY, SOURCE_ROW_NO, REJECT_REASON
FROM TMP_MEMBERS_PARSED
WHERE REJECT_REASON IS NOT NULL;



