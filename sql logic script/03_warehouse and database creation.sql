-- credit monitior

CREATE RESOURCE MONITOR IF NOT EXISTS incubyte_monitior
  WITH CREDIT_QUOTA = 200
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS ON 75  PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND
           ON 110 PERCENT DO SUSPEND_IMMEDIATE;

-- warehouse creation

CREATE WAREHOUSE IF NOT EXISTS incubyte_wh
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  STATEMENT_TIMEOUT_IN_SECONDS = 1800
  STATEMENT_QUEUED_TIMEOUT_IN_SECONDS = 600;

use warehouse incubyte_wh;

ALTER WAREHOUSE incubyte_wh
SET RESOURCE_MONITOR = incubyte_monitior;


-- database and schema creation

USE ROLE ACCOUNTADMIN;

USE WAREHOUSE incubyte_wh;

CREATE DATABASE IF NOT EXISTS INCUBYTE_ASSESSMENT;

CREATE SCHEMA IF NOT EXISTS INCUBYTE_ASSESSMENT.BRONZE;

CREATE SCHEMA IF NOT EXISTS INCUBYTE_ASSESSMENT.SILVAR;

CREATE SCHEMA IF NOT EXISTS INCUBYTE_ASSESSMENT.GOLD;









