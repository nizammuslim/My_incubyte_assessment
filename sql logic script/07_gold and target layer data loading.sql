-- STG_MEMBERS -> MEMBERS_AUS / MEMBERS_USA / MEMBERS_IND   ("latest record wins")
-- The same Member_ID in two country files means the member moved. Only the NEWEST record survives,
-- and it goes only to the table of its own country.

USE ROLE ACCOUNTADMIN;

USE WAREHOUSE incubyte_wh;

USE DATABASE INCUBYTE_ASSESSMENT;

USE SCHEMA INCUBYTE_ASSESSMENT.GOLD;

INSERT  INTO INCUBYTE_ASSESSMENT.SILVAR.STG_LATEST_MEMBERS
    (MEMBER_ID, MEMBER_NAME, EMAIL, DOB, COUNTRY, FLIGHT_DATE, TIER,
     AGE, STALE_MEMBER, SOURCE_FILE, SOURCE_COUNTRY, SOURCE_ROW_NO, AS_OF_DATE)
SELECT
    MEMBER_ID, MEMBER_NAME, EMAIL, DOB, COUNTRY, FLIGHT_DATE, TIER,
    AGE, STALE_MEMBER, SOURCE_FILE, SOURCE_COUNTRY, SOURCE_ROW_NO, AS_OF_DATE
FROM INCUBYTE_ASSESSMENT.SILVAR.STG_MEMBERS
QUALIFY ROW_NUMBER() OVER (
            PARTITION BY MEMBER_ID
            ORDER BY FLIGHT_DATE DESC NULLS LAST,    
                     SOURCE_FILE ASC,
                     SOURCE_ROW_NO DESC
        ) = 1;

-- Step 2: send every survivor to the table of its country.
INSERT INTO INCUBYTE_ASSESSMENT.GOLD.MEMBERS_AUS
    (MEMBER_ID, MEMBER_NAME, EMAIL, DOB, COUNTRY, FLIGHT_DATE, TIER,
     AGE, STALE_MEMBER, SOURCE_FILE, SOURCE_COUNTRY, SOURCE_ROW_NO, AS_OF_DATE)
SELECT
    MEMBER_ID, MEMBER_NAME, EMAIL, DOB, COUNTRY, FLIGHT_DATE, TIER,
    AGE, STALE_MEMBER, SOURCE_FILE, SOURCE_COUNTRY, SOURCE_ROW_NO, AS_OF_DATE
FROM INCUBYTE_ASSESSMENT.SILVAR.STG_LATEST_MEMBERS
WHERE COUNTRY = 'AUS';

INSERT INTO INCUBYTE_ASSESSMENT.GOLD.INCUBYTE_ASSESSMENT.GOLD.MEMBERS_USA
    (MEMBER_ID, MEMBER_NAME, EMAIL, DOB, COUNTRY, FLIGHT_DATE, TIER,
     AGE, STALE_MEMBER, SOURCE_FILE, SOURCE_COUNTRY, SOURCE_ROW_NO, AS_OF_DATE)
SELECT
    MEMBER_ID, MEMBER_NAME, EMAIL, DOB, COUNTRY, FLIGHT_DATE, TIER,
    AGE, STALE_MEMBER, SOURCE_FILE, SOURCE_COUNTRY, SOURCE_ROW_NO, AS_OF_DATE
FROM INCUBYTE_ASSESSMENT.SILVAR.STG_LATEST_MEMBERS
WHERE COUNTRY = 'USA';

INSERT INTO INCUBYTE_ASSESSMENT.GOLD.MEMBERS_IND
    (MEMBER_ID, MEMBER_NAME, EMAIL, DOB, COUNTRY, FLIGHT_DATE, TIER,
     AGE, STALE_MEMBER, SOURCE_FILE, SOURCE_COUNTRY, SOURCE_ROW_NO, AS_OF_DATE)
SELECT
    MEMBER_ID, MEMBER_NAME, EMAIL, DOB, COUNTRY, FLIGHT_DATE, TIER,
    AGE, STALE_MEMBER, SOURCE_FILE, SOURCE_COUNTRY, SOURCE_ROW_NO, AS_OF_DATE
FROM INCUBYTE_ASSESSMENT.SILVAR.STG_LATEST_MEMBERS
WHERE COUNTRY = 'IND';